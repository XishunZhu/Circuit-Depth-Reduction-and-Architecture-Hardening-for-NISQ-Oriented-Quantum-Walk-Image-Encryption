def _font(run, cn="宋体", en="Times New Roman", size=10.5, bold=False, italic=False, color=None):
    run.font.name = en
    run._element.rPr.rFonts.set(qn('w:eastAsia'), cn)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = RGBColor(*color)


def P(text, size=10.5, bold=False, italic=False, align="j", cn="宋体", space_after=5,
      indent=True, color=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    _font(r, cn=cn, size=size, bold=bold, italic=italic, color=color)
    p.alignment = {"c": WD_ALIGN_PARAGRAPH.CENTER, "j": WD_ALIGN_PARAGRAPH.JUSTIFY,
                   "l": WD_ALIGN_PARAGRAPH.LEFT}[align]
    if indent and align == "j":
        p.paragraph_format.first_line_indent = Pt(size * 2)
    p.paragraph_format.space_after = Pt(space_after)
    return p


def H(text, level=1):
    h = doc.add_heading("", level=level)
    r = h.add_run(text)
    _font(r, cn="黑体", en="Times New Roman",
          size={1: 14, 2: 12, 3: 11}[level], bold=True, color=(0x12, 0x32, 0x4F))
    h.paragraph_format.space_before = Pt(10 if level == 1 else 6)
    h.paragraph_format.space_after = Pt(5)
    return h


def EQ(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    _font(r, cn="宋体", en="Cambria Math", size=10.5, italic=True)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(6)
    return p


def TBL(caption, header, rows, widths=None, fontsize=8.5):
    c = doc.add_paragraph()
    rr = c.add_run(caption)
    _font(rr, cn="黑体", size=9, bold=True)
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.space_after = Pt(2)
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(header):
        cell = t.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(str(h))
        _font(run, cn="黑体", size=fontsize, bold=True)
        cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(str(v))
            _font(run, cn="宋体", size=fontsize)
            if i > 0:
                cells[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Inches(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def FIG(name, caption, width=6.0):
    doc.add_picture(os.path.join(OUTD, name), width=Inches(width))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    p = doc.add_paragraph()
    r = p.add_run(caption)
    _font(r, cn="黑体", size=9)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(10)




def STEP(label, text, size=10.5):
    """带粗体步骤标签的正文段落（悬挂缩进，便于阅读加解密步骤）。"""
    p = doc.add_paragraph()
    r1 = p.add_run(label)
    _font(r1, cn="黑体", size=size, bold=True)
    r2 = p.add_run(text)
    _font(r2, cn="宋体", size=size)
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.left_indent = Pt(21)
    p.paragraph_format.first_line_indent = Pt(-21)
    p.paragraph_format.space_after = Pt(3)
    return p

